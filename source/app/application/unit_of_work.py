"""Persistence ports implemented by infrastructure."""

from __future__ import annotations

from datetime import datetime
from typing import Any, Protocol

from app.domain.audit import AuditEvent
from app.domain.household import Household, Member, Relationship
from app.domain.initiative import InitiativeDecision
from app.domain.memory import MemoryRecord
from app.domain.need import NeedHypothesis
from app.domain.observation import Observation
from app.domain.situation import SituationRecord


class HouseholdRepository(Protocol):
    def add(self, household: Household) -> None: ...
    def get(self, household_id: str) -> Household | None: ...
    def update(self, household: Household, expected_version: int) -> Household: ...


class MemberRepository(Protocol):
    def add(self, member: Member) -> None: ...
    def get(self, household_id: str, member_id: str) -> Member | None: ...
    def update(self, member: Member, expected_version: int) -> Member: ...


class RelationshipRepository(Protocol):
    def add(self, relationship: Relationship) -> None: ...
    def get(self, household_id: str, relationship_id: str) -> Relationship | None: ...
    def update(self, relationship: Relationship, expected_version: int) -> Relationship: ...


class ObservationRepository(Protocol):
    def append(self, observation: Observation) -> None: ...
    def get(self, household_id: str, observation_id: str) -> Observation | None: ...


class AuditRepository(Protocol):
    def append(self, event: AuditEvent) -> None: ...


class ReplayRepository(Protocol):
    def get(self, household_id: str, command_id: str) -> dict[str, Any] | None: ...
    def add(self, record: dict[str, Any]) -> None: ...


class OutboxRepository(Protocol):
    def append(self, record: dict[str, Any]) -> None: ...


class MemoryRepository(Protocol):
    def add(self, memory: MemoryRecord) -> None: ...
    def get(self, household_id: str, memory_id: str) -> MemoryRecord | None: ...
    def get_active(
        self, household_id: str, subject_id: str, memory_type: str, memory_key: str
    ) -> MemoryRecord | None: ...
    def get_active_for_key(
        self, household_id: str, subject_id: str, memory_key: str
    ) -> MemoryRecord | None: ...
    def update(self, memory: MemoryRecord, expected_version: int, expected_status: str) -> None: ...
    def list_all(self, household_id: str) -> tuple[MemoryRecord, ...]: ...
    def list_visible(
        self, *, household_id: str, principal_id: str, subject_ids: tuple[str, ...],
        delegated_subject_ids: tuple[str, ...], as_of: datetime,
        memory_types: tuple[str, ...], keywords: tuple[str, ...], limit: int,
    ) -> tuple[MemoryRecord, ...]: ...


class ContextRepository(Protocol):
    def list_members(self, household_id: str, member_ids: tuple[str, ...]) -> tuple[Member, ...]: ...
    def list_relationships(self, household_id: str, member_ids: tuple[str, ...]) -> tuple[Relationship, ...]: ...
    def list_observations(
        self, *, household_id: str, principal_id: str, subject_ids: tuple[str, ...],
        delegated_subject_ids: tuple[str, ...], as_of: datetime, not_before: datetime,
        keywords: tuple[str, ...], limit: int,
    ) -> tuple[Observation, ...]: ...


class SituationRepository(Protocol):
    def add(self, situation: SituationRecord) -> None: ...
    def get(self, household_id: str, situation_id: str) -> SituationRecord | None: ...
    def get_current(self, household_id: str) -> SituationRecord | None: ...
    def update_status(
        self, situation: SituationRecord, expected_version: int, expected_status: str
    ) -> None: ...
    def list_all(self, household_id: str) -> tuple[SituationRecord, ...]: ...


class NeedRepository(Protocol):
    def add(self, need: NeedHypothesis) -> None: ...
    def get(self, household_id: str, need_id: str) -> NeedHypothesis | None: ...
    def count(self, household_id: str) -> int: ...


class InitiativeRepository(Protocol):
    def add(self, decision: InitiativeDecision) -> None: ...
    def get(self, household_id: str, initiative_id: str) -> InitiativeDecision | None: ...
    def count(self, household_id: str) -> int: ...


class UnitOfWork(Protocol):
    households: HouseholdRepository
    members: MemberRepository
    relationships: RelationshipRepository
    observations: ObservationRepository
    audit: AuditRepository
    replays: ReplayRepository
    outbox: OutboxRepository
    memories: MemoryRepository
    situations: SituationRepository
    needs: NeedRepository
    initiatives: InitiativeRepository
    context: ContextRepository

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, exc_type: object, exc: object, traceback: object) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
